                            dl.SchoolStudentId.HasValue &&
                            allStudentVersionIds.Contains(dl.SchoolStudentId.Value)))
                        .Where(d => d.IsLastVersion && d.DocumentTypeId == request.DocumentTypeId)
                        .AnyAsync();
                }
                else
