                    alreadyExists = await _context.Documents
                        .Include(d => d.DocumentLinks)
                        .Where(d => d.DocumentLinks.Any(dl => dl.EntityId == request.EntityId))
                        .Where(d => d.IsLastVersion && d.DocumentTypeId == request.DocumentTypeId)
                        .AnyAsync();
